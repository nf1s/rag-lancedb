#!/usr/bin/env bash
# Resolve the Mac's address as seen from the Colima VM and write deploy/local.values.yaml.
set -euo pipefail
cd "$(dirname "$0")/.."

LLM_PORT="${LLM_PORT:-1234}"
LLM_MODEL="${LLM_MODEL:-qwen2.5-7b-instruct}"

resolve_host() {
  local candidate
  for candidate in host.lima.internal host.docker.internal; do
    candidate_ip="$(colima ssh -- getent hosts "${candidate}" 2>/dev/null | awk '{print $1}' | head -n1 || true)"
    if [[ -n "${candidate_ip}" ]]; then
      echo "${candidate_ip}"
      return 0
    fi
  done
  # Lima's default gateway is the host side of the VM network.
  colima ssh -- ip route show default 2>/dev/null | awk '{print $3}' | head -n1
}

HOST_IP="$(resolve_host)"
if [[ -z "${HOST_IP}" ]]; then
  echo "could not determine the host address from colima; is it running?" >&2
  exit 1
fi

mkdir -p deploy
cat > deploy/local.values.yaml <<EOF
# Generated by scripts/gen-local-values.sh -- do not commit.
llm:
  baseUrl: "http://${HOST_IP}:${LLM_PORT}/v1"
  model: "${LLM_MODEL}"
api:
  devReload: true
ui:
  devReload: true
EOF

echo "wrote deploy/local.values.yaml"
echo "  LLM: http://${HOST_IP}:${LLM_PORT}/v1  model=${LLM_MODEL}"
echo "  (make sure the server binds 0.0.0.0, not 127.0.0.1)"
